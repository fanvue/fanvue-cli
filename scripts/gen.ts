import { deriveCommands } from "../src/codegen/derive.ts";

const spec = (name: string) => Bun.file(new URL(`../spec/${name}`, import.meta.url)).json();
const [v1, v0] = await Promise.all([spec("v1.json"), spec("v0.json")]);

const commands = deriveCommands([v1, v0]);

await Bun.write(
  new URL("../src/commands/public.gen.ts", import.meta.url),
  `// Generated by scripts/gen.ts from spec/. Do not edit; run \`bun run gen\`.
import type { CommandSpec } from "./types.ts";

export const publicCommands: CommandSpec[] = ${JSON.stringify(commands, null, 2)};
`,
);

const tree = commands
  .map(
    (c) =>
      `fanvue ${[...c.command, ...c.args.map((a) => `<${a}>`)].join(" ")}`.padEnd(70) +
      `${c.gate.padEnd(11)}${c.method} ${c.path}`,
  )
  .join("\n");
await Bun.write(
  new URL("../docs/commands.txt", import.meta.url),
  `# Generated by scripts/gen.ts. ${commands.length} commands.\n\n${tree}\n`,
);

const apiVersion = v1.components?.parameters?.ApiVersionHeader?.schema?.default;
if (typeof apiVersion !== "string") throw new Error("spec has no ApiVersionHeader default");
await Bun.write(
  new URL("../src/commands/api-version.gen.ts", import.meta.url),
  `// Generated by scripts/gen.ts from the spec's ApiVersionHeader default. Do not edit.
export const API_VERSION = ${JSON.stringify(apiVersion)};
`,
);

console.log(`${commands.length} commands`);
