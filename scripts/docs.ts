// Writes the CLI command reference page for the docs site from the same tree the binary uses.
import { loadCommands } from "../src/commands/registry.ts";
import type { CommandSpec } from "../src/commands/types.ts";

const publicCommands = await loadCommands();

const GROUP_TITLES: Record<string, string> = {
  messages: "Messages",
  fans: "Fans",
  vault: "Vault",
  posts: "Posts",
  insights: "Insights",
  links: "Links",
  promotions: "Promotions",
  account: "Account",
  agency: "Agency",
  webhooks: "Webhooks",
  apps: "Apps",
};

const CONFIRMATION = { read: "None", write: "Yes", "fan-facing": "Handle" } as const;

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\$/g, "\\$").replace(/\n/g, " ");

function row(c: CommandSpec) {
  const usage = ["fanvue", ...c.command, ...c.args.map((a) => `<${a}>`)].join(" ");
  const agency = c.creatorPath ? "Yes" : "No";
  return `| \`${usage}\` | ${cell(c.summary)} | ${CONFIRMATION[c.gate]} | ${agency} | \`${c.method} ${c.path}\` |`;
}

const sections = Object.entries(GROUP_TITLES).map(([group, title]) => {
  const rows = publicCommands.filter((c) => c.command[0] === group).map(row);
  return `## ${title}

| Command | What it does | Confirmation | \`--creator\` | API operation |
| --- | --- | --- | --- | --- |
${rows.join("\n")}`;
});

const page = `---
title: "Fanvue CLI command reference"
sidebarTitle: "Command reference"
description: "Every Fanvue CLI command, the API operation it sends, whether it asks for confirmation and whether it takes --creator."
---

{/* Generated by fanvue-cli scripts/docs.ts. Edit the generator, not this page. */}

Each command sends one documented API operation. Run any command with \`--help\` for its flags, which are the operation's query parameters and body fields under their API names.

The **Confirmation** column shows what a command needs before it sends. \`None\` sends straight away. \`Yes\` needs \`--yes\`. \`Handle\` changes something fans see or pay for, so it needs \`--confirm <your handle>\`. Add \`--interactive\` to be asked at the terminal instead. The **\`--creator\`** column shows which commands an agency can run for a creator it manages.

${sections.join("\n\n")}
`;

await Bun.write(new URL("../docs/mintlify/cli/commands.mdx", import.meta.url), page);
console.log(`docs/mintlify/cli/commands.mdx: ${publicCommands.length} commands`);
